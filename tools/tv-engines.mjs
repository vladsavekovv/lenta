// What each Samsung television's web engine has, and what it has not.
//
//   cd tools && npm install --no-save @mdn/browser-compat-data && node tv-engines.mjs
//
// Writes tests/tv-engines.json, which tests/test_tv_models.py and tests/test_legacy_builtins.py read.
// Those two tests take a modern browser, delete from it everything a given television does not have,
// and run LENTA in the hole that leaves. The list below is what they delete, and it is generated
// rather than written out by hand for one reason: a hand-written list only ever contains the things
// somebody already knew were missing, which is exactly the set of things that are not going to break.
//
// The dependency is not in package.json on purpose. It is twenty megabytes, it is only needed to
// refresh this file, and `npm run legacy` — the thing anyone changing the client actually runs —
// should not have to download it. Re-run this when a new model year appears, or after a year or two,
// and look at the diff.
//
// Model year to engine, from Samsung's own table at
// developer.samsung.com/smarttv/develop/specifications/web-engine-specifications.html:
//
//   2017 Tizen 3.0 M47    2020 Tizen 5.5 M69    2023 Tizen 7.0 M94     2026 Tizen 10.0 M130
//   2018 Tizen 4.0 M56    2021 Tizen 6.0 M76    2024 Tizen 8.0 M108
//   2019 Tizen 5.0 M63    2022 Tizen 6.5 M85    2025 Tizen 9.0 M120
//
// index.html sends 2017-2022 the built client in web/legacy/ and everything newer the normal one.
// The line falls there because the test is for aspect-ratio, which arrived in Chromium 88.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const bcd = (await import('@mdn/browser-compat-data', { with: { type: 'json' } })).default;
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'tests', 'tv-engines.json');

const YEARS = [[2017, 47], [2018, 56], [2019, 63], [2020, 69], [2021, 76], [2022, 85],
               [2023, 94], [2024, 108], [2025, 120], [2026, 130]];
// The floor of each built client: 47 is a 2017 set, 63 a 2019 one. Both get a list of the language
// they have not got, because core-js is trimmed to what the client uses in both and a polyfill left
// out by mistake is invisible on any browser that still has the built-in natively.
const FLOORS = [47, 63];

// The interfaces a media client touches. Everything else in the web platform — Bluetooth, payments,
// WebGPU — LENTA never reaches for, and listing it would only make the file long and the test slow.
const IFACES = [
  'Element', 'Node', 'Document', 'DocumentFragment', 'CharacterData', 'Text', 'ShadowRoot',
  'HTMLElement', 'HTMLMediaElement', 'HTMLVideoElement', 'HTMLAudioElement', 'HTMLInputElement',
  'HTMLSelectElement', 'HTMLFormElement', 'HTMLImageElement', 'HTMLCanvasElement', 'HTMLDialogElement',
  'HTMLSlotElement', 'HTMLTemplateElement', 'HTMLAnchorElement', 'HTMLScriptElement',
  'DOMTokenList', 'NodeList', 'HTMLCollection', 'NamedNodeMap', 'DOMRect', 'DOMRectReadOnly',
  'CSSStyleDeclaration', 'CSSStyleSheet', 'StyleSheetList', 'MediaQueryList',
  'Event', 'EventTarget', 'CustomEvent', 'KeyboardEvent', 'MouseEvent', 'PointerEvent', 'TouchEvent',
  'Window', 'Navigator', 'Location', 'History', 'Storage', 'Screen', 'Performance',
  'URL', 'URLSearchParams', 'FormData', 'Headers', 'Request', 'Response', 'AbortController',
  'AbortSignal', 'Blob', 'File', 'FileReader', 'FileList', 'ReadableStream',
  'IntersectionObserver', 'IntersectionObserverEntry', 'ResizeObserver', 'ResizeObserverEntry',
  'MutationObserver', 'TextTrack', 'TextTrackList', 'TextTrackCue', 'VTTCue', 'TimeRanges',
  'MediaSession', 'MediaMetadata', 'MediaSource', 'SourceBuffer', 'VideoPlaybackQuality',
  'Range', 'Selection', 'XMLHttpRequest', 'WebSocket', 'Clipboard', 'CSS', 'Animation',
  'DataTransfer', 'PromiseRejectionEvent',
];

// The language, for the oldest engine only: core-js is what puts it back, and core-js is only in the
// built client, which every set from 2017 to 2022 is given.
const BUILTINS = ['Array', 'Object', 'String', 'Number', 'Math', 'JSON', 'Promise', 'Symbol',
                  'Map', 'Set', 'WeakMap', 'WeakSet', 'RegExp', 'Function', 'Date', 'Error',
                  'Reflect', 'Proxy', 'globalThis', 'TypedArray', 'ArrayBuffer'];

function chrome(node) {
  const c = node?.__compat?.support?.chrome;
  const first = Array.isArray(c) ? c[c.length - 1] : c;
  const v = first?.version_added;
  if (v === true) return 1;
  if (typeof v !== 'string') return null;
  const n = parseFloat(v);
  return Number.isFinite(n) ? n : null;
}

const out = { note: 'Generated by tools/tv-engines.mjs from @mdn/browser-compat-data — do not edit.',
              generated: new Date().toISOString().slice(0, 10), years: {}, builtins: {} };

for (const [year, m] of YEARS) {
  const members = [], globals = [];
  for (const iface of IFACES) {
    const def = bcd.api[iface];
    if (!def) continue;
    const v = chrome(def);
    if (v !== null && v > m) { globals.push(iface); continue; }
    for (const [name, node] of Object.entries(def)) {
      if (name.startsWith('__') || name.includes('_')) continue;
      const mv = chrome(node);
      if (mv !== null && mv > m) members.push([iface, name]);
    }
  }
  out.years[year] = { chrome: m, legacy: m < 88, members, globals };
}

for (const floor of FLOORS) {
  const statics = [], protos = [];
  for (const name of BUILTINS) {
    const def = bcd.javascript.builtins[name];
    if (!def) continue;
    for (const [k, node] of Object.entries(def)) {
      if (k.startsWith('__') || k.includes('_')) continue;
      const v = chrome(node);
      if (v === null || v <= floor) continue;
      (['Array', 'String', 'Object', 'Function', 'RegExp', 'Promise', 'Map', 'Set', 'Date',
        'Number', 'TypedArray', 'ArrayBuffer', 'Error'].includes(name) ? protos : statics).push([name, k]);
    }
  }
  out.builtins[floor] = { chrome: floor, statics, protos };
}

writeFileSync(OUT, JSON.stringify(out));
const n = Object.entries(out.years).map(([y, v]) => `${y}:${v.members.length}`).join(' ');
console.log(`tests/tv-engines.json written — members newer than each year's engine: ${n}`);
for (const floor of FLOORS) {
  const b = out.builtins[floor];
  console.log(`and ${b.statics.length + b.protos.length} built-ins newer than Chromium ${floor}`);
}
